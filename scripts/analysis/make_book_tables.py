# 2. RESET test + learning curve
# --------------------------------------------------------------------------
def table_nonlinear_reset():
    df = _read("nonlinear_reset.csv")
    if df is None:
        return
    rows = []
    for _, r in df.iterrows():
        p = float(r["reset_p"])
        pstr = "$<10^{-3}$" if p < 1e-3 else f"{p:.4f}"
        verdict = "reject" if bool(r["reject_linear_at_5pct"]) else "no reject"
        rows.append([r"\texttt{" + _esc(r["basket"]) + "}", f"{int(r['n_train'])}",
                     pstr, verdict])
    _write_table(
        os.path.join(RTAB, "nonlinear_reset.tex"),
        "Ramsey RESET $F$-test of the linear forecasting equation, fitted on the "
        "training sample only ($H_0$: no omitted nonlinearity). Linearity survives on "
        "the \\texttt{ADBE} basket used throughout Phases 4--8 and is rejected on the "
        "other three.",
        "tab:nonlinear_reset",
        ["Basket", "$n_{\\text{train}}$", "RESET $p$", "Verdict at 5\\%"],
        rows, "lrrl",
        note="Source: \\code{results/tables/nonlinear_reset.csv} via "
             "\\code{scripts/analysis/compare_nonlinear.py}.")


def table_nonlinear_learning():
    df = _read("nonlinear_learning.csv")
    if df is None:
        return
    rows = [[f"{int(r['train_bars'])}", f"{r['oos_mse']:.3e}", f"{r['oos_r2']:+.4f}"]
            for _, r in df.iterrows()]
    _write_table(
        os.path.join(RTAB, "nonlinear_learn.tex"),
        "Gradient-boosting learning curve: out-of-sample fit on a fixed 2019--2020 "
        "validation window as the causal training sample grows. The ensemble is still "
        "inside its own variance-dominated regime until roughly 2{,}400--2{,}800 "
        "training bars, which is about as much data as this universe provides.",
        "tab:nonlinear_learning",
        ["Training bars", "OOS MSE", "OOS $R^2$"],
        rows, "rrr",
        note="Source: \\code{results/tables/nonlinear_learning.csv}.")


