#!/usr/bin/env python3
"""make_book_tables.py — emit the extra LaTeX tables the book-length report needs,
and compute the statistical-power / deflated-Sharpe analysis of Chapter 10.

Everything here is derived from CSVs already written by the analysis scripts in
scripts/analysis/ (nothing is hand-typed). Outputs:

  report/tables/engine_latency.tex    per-stage p50/p95/p99 from results/tables/engine_latency.csv
  report/tables/nonlinear_reset.tex   RESET p-values          (nonlinear_reset.csv)
  report/tables/nonlinear_learn.tex   GBM learning curve      (nonlinear_learning.csv)
  report/tables/multtest_dm.tex       Diebold-Mariano forest  (multtest_dm.csv)
  report/tables/multtest_hac.tex      per-strategy HAC audit  (multtest_audit.csv)
  report/tables/power_dsr.tex         power / deflated Sharpe (computed here)
  results/tables/power_dsr.csv        the same numbers as CSV (machine-readable)

Power / deflated-Sharpe methodology (Chapter 10 of the report):
  * required sample size T* = (z / SR_daily)^2 days, for z = 1.645 (one-sided 5%)
    and z = Phi^{-1}(1 - alpha/M) (Bonferroni over the audited M);
  * Bailey & Lopez de Prado (2014): expected maximum Sharpe under the null,
        SR0 = sqrt(V[SR]) * ((1-g) * Phi^{-1}(1-1/N) + g * Phi^{-1}(1-1/(N e))),
    and the deflated Sharpe ratio
        DSR = Phi( (SR_hat - SR0) * sqrt(T-1)
                   / sqrt(1 - skew*SR_hat + (kurt-1)/4 * SR_hat^2) );
  * effective number of independent trials from the eigenvalue spectrum of the
    (T, M) daily-P&L correlation matrix: M_eff = (sum l)^2 / sum l^2
    (the participation ratio), plus the mean pairwise correlation;
  * stationary-bootstrap percentile CI for the best strategy's Sharpe.

Run: python3 scripts/analysis/make_book_tables.py
"""
import csv
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TAB = os.path.join(ROOT, "results", "tables")
RTAB = os.path.join(ROOT, "report", "tables")
sys.path.insert(0, os.path.join(ROOT, "scripts"))
sys.path.insert(0, os.path.join(ROOT, "scripts", "statkit"))
os.makedirs(RTAB, exist_ok=True)

BARS_PER_YEAR = 252.0
EULER = 0.5772156649015329


def _read(name):
    p = os.path.join(TAB, name)
    if not os.path.exists(p):
        return None
    return pd.read_csv(p)


def _esc(s):
    return (str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
            .replace("#", r"\#"))


def _write_table(path, caption, label, header, rows, colfmt=None, note=None):
    ncol = len(header)
    if colfmt is None:
        colfmt = "l" + "r" * (ncol - 1)
    out = [r"% Generated by scripts/analysis/make_book_tables.py -- do not edit.",
           r"\begin{table}[H]\centering\small",
           r"\begin{threeparttable}",
           rf"\caption{{{caption}}}",
           rf"\label{{{label}}}",
           rf"\begin{{tabular}}{{{colfmt}}}",
           r"\toprule",
           " & ".join(header) + r" \\",
           r"\midrule"]
    for r in rows:
        out.append(" & ".join(str(c) for c in r) + r" \\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    if note:
        out.append(r"\begin{tablenotes}\footnotesize\item " + note + r"\end{tablenotes}")
    out.append(r"\end{threeparttable}")
    out.append(r"\end{table}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)}")


# --------------------------------------------------------------------------
# 1. Engine per-stage latency
# --------------------------------------------------------------------------
def table_engine_latency():
    df = _read("engine_latency.csv")
    if df is None:
        return
    rows = []
    for _, r in df.iterrows():
        rows.append([r"\texttt{" + _esc(r["stage"]) + "}",
                     f"{r['p50_ns']:.1f}", f"{r['p95_ns']:.1f}", f"{r['p99_ns']:.1f}",
                     f"{r['mean_ns']:.1f}"])
    _write_table(
        os.path.join(RTAB, "engine_latency.tex"),
        "Per-stage latency of the C++ pipeline over 30{,}000 synthetic bars "
        "(\\code{build/statarbsim --demo}). Percentiles are lower edges of "
        "logarithmically spaced histogram buckets of width $\\times1.158$ over "
        "$[10\\,\\mathrm{ns},100\\,\\mu\\mathrm{s}]$; identical p50/p95/p99 means those "
        "quantiles share one bucket, not that the distribution is degenerate.",
        "tab:engine_latency",
        ["Stage", "p50 (ns)", "p95 (ns)", "p99 (ns)", "mean (ns)"],
        rows,
        note="Source: \\code{results/tables/engine_latency.csv}, captured by "
             "\\code{scripts/analysis/capture_engine_bench.py}.")


