#!/usr/bin/env python3
"""Render the C++ engine latency histogram + microbenchmark figures and a LaTeX
benchmark table for report Section 9, from the captured CSVs."""
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TAB = os.path.join(ROOT, "results", "tables")
FIG = os.path.join(ROOT, "results", "figures")
REPORT_FIG = os.path.join(ROOT, "report", "figures")
os.makedirs(FIG, exist_ok=True)
os.makedirs(REPORT_FIG, exist_ok=True)


def main():
    lat = pd.read_csv(os.path.join(TAB, "engine_latency.csv"))
    bench = pd.read_csv(os.path.join(TAB, "engine_bench.csv"))

    plt.style.use("seaborn-v0_8-whitegrid")

    # ---- latency histogram (grouped p50/p95/p99 by stage) ----
    stages = lat["stage"].tolist()
    x = np.arange(len(stages))
    width = 0.26
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.bar(x - width, lat["p50_ns"], width, label="p50", color="#4C72B0")
    ax.bar(x, lat["p95_ns"], width, label="p95", color="#DD8452")
    ax.bar(x + width, lat["p99_ns"], width, label="p99", color="#55A868")
    ax.set_xticks(x)
    ax.set_xticklabels(stages, rotation=15)
    ax.set_ylabel("ns / bar")
    ax.set_title("Per-stage latency distribution (C++ engine, 30k synthetic bars)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "latency_hist.png"), dpi=150)
    plt.close(fig)

    # ---- microbenchmark comparison ----
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    # vector vs deque
    vd = bench[bench["bench"] == "vector_vs_deque"]
    if len(vd):
        ax = axes[0]
        ax.bar(["std::vector\n(contiguous)", "std::deque"], [vd['a'].iloc[0], vd['b'].iloc[0]],
               color=["#4C72B0", "#C44E52"])
        ax.set_ylabel("ns / rolling-window step")
        ax.set_title(f"Rolling-window sweep\ndeque/vector = {vd['ratio'].iloc[0]:.2f}x")
    sa = bench[bench["bench"] == "soa_vs_aos"]
    if len(sa):
        ax = axes[1]
        ax.bar(["Structure-of-Arrays", "Array-of-Structures"], [sa['a'].iloc[0], sa['b'].iloc[0]],
               color=["#55A868", "#8172B3"])
        ax.set_ylabel("ns / column reduction (1M)")
        ax.set_title(f"SoA vs AoS column reduction\naos/soa = {sa['ratio'].iloc[0]:.2f}x")
    fig.suptitle("Cache-efficiency microbenchmarks (measured)")
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "cache_bench.png"), dpi=150)
    plt.close(fig)

    # copy into report/figures
    import shutil
    for f in ("latency_hist.png", "cache_bench.png"):
        shutil.copy2(os.path.join(FIG, f), os.path.join(REPORT_FIG, f))

    # ---- LaTeX benchmark table fragment ----
    lines = ["% Auto-generated by scripts/plotting/render_engine_results.py"]
    lines.append("\\begin{table}[H]\\centering\\small")
    lines.append("\\caption{Per-stage latency of the C++ pipeline (30,000 synthetic bars) "
                 "and cache-efficiency microbenchmarks. Values from live runs "
                 "(\\texttt{capture\\_engine\\_bench.py}); nothing hand-typed.}")
    lines.append("\\label{tab:engine_bench}")
    lines.append("\\begin{tabular}{lrrr}\\toprule")
    lines.append("\\textbf{Stage} & \\textbf{p50 (ns)} & \\textbf{p95 (ns)} & \\textbf{p99 (ns)}\\\\ \\midrule")
    for _, r in lat.iterrows():
        stage = r["stage"].replace("_", "\\_")
        lines.append("%s & %.1f & %.1f & %.1f \\\\" % (stage, r["p50_ns"], r["p95_ns"], r["p99_ns"]))
    lines.append("\\midrule")
    for _, r in bench.iterrows():
        lines.append("\\multicolumn{4}{l}{\\emph{%s}: %.1f vs %.1f %s (ratio %.2fx)}\\\\"
                     % (r["bench"], r["a"], r["b"], r["a_unit"], r["ratio"]))
    lines.append("\\bottomrule\\end{tabular}\\end{table}")
    out = os.path.join(ROOT, "report", "tables", "engine_bench.tex")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote results/figures/{latency_hist,cache_bench}.png and report/tables/engine_bench.tex")


if __name__ == "__main__":
    main()
